'''

------ IDENTITY  OPERATORS ------

-->--> Identity operators also returns two confitions either true or false.`
--> If the condition is true it returns true.
--> If the condition is false it returns false.

------ TYPES ------

1.is
2.is not

'''

word1=str(input("enter the word:"))
word2=str(input("enter the word:"))

print(word1 is word2)
print(word1 == word2)
print(word1 is not word2)

# = --> assign the value to the variable
#  == --> checks whether the two values are equal or not. If they are equal it returns true else it returns false. 

